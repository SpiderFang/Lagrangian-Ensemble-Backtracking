import re
# 「站」→「地點」：僅用於指稱五個研究地點之處（測站、觀測站等不在此列；轉換後以全文檢索逐一確認）
RULES = [
    ('於各站段落逐站說明', '於各地點段落逐一說明'),
    ('各站來源方位與條件式來源足跡逐站說明如下', '各地點之來源方位與條件式來源足跡逐一說明如下'),
    ('以下逐站呈現', '以下依地點逐一呈現'),
    ('占全站穿越點之比例', '占該地點全部穿越點之比例'),
    ('占全站總量之比例', '占該地點停留時數總量之比例'),
    ('5 處研究站點', '5 處研究地點'),
    ('5 個站', '5 個地點'),
    ('五站', '五個地點'), ('四站', '四個地點'), ('三站', '三個地點'),
    ('每站', '每個地點'), ('各站', '各地點'), ('同一站', '同一地點'),
    ('該站', '該地點'), ('本站', '本地點'), ('某站', '某地點'),
    ('站名', '地點名稱'), ('站點', '地點'),
]
def to_loc(s):
    for a, b in RULES: s = s.replace(a, b)
    # 規則 1：五個研究區域一律稱「研究地點」，不單用「地點」
    s = re.sub(r'(?<!研究)地點', '研究地點', s)
    # 規則 2：本案 → 本研究
    s = s.replace('本案設定', '本研究設定').replace('本案', '本研究')
    # 規則 3：粒子 → 虛擬質點（既有方法名稱「拉格朗日粒子…」除外）
    s = re.sub(r'(?<!拉格朗日)粒子', '虛擬質點', s)
    # 規則 4：完整罐／瓶（身、體）→ 完整進水罐／瓶
    s = re.sub(r'完整(?!進水)(?:罐身|罐體|罐)', '完整進水罐', s)
    s = re.sub(r'完整(?!進水)(?:瓶身|瓶體|瓶)', '完整進水瓶', s)
    # 規則 5：壓扁瓶身 → 半壓扁瓶身（已有「半」「嚴重」者不動）
    s = re.sub(r'(?<!半)(?<!嚴重)壓扁瓶身', '半壓扁瓶身', s)
    return s
